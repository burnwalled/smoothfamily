"use client";

// Connect an authenticator app (Microsoft/Google Authenticator, 1Password …):
// scan the QR code – or on the phone itself, tap the link / type the key –
// then confirm with the first 6-digit code.
import { useState } from "react";
import { useI18n } from "@/lib/i18n";

export type TotpSetup = { secret: string; otpauth_uri: string; qr_svg: string };

export function CodeInput({ value, onChange, autoFocus = false }: { value: string; onChange: (v: string) => void; autoFocus?: boolean }) {
  const { t } = useI18n();
  return (
    <input
      className="input text-center font-mono text-xl tracking-[0.4em]"
      inputMode="numeric"
      autoComplete="one-time-code"
      maxLength={6}
      placeholder="000000"
      aria-label={t("mfa.code")}
      autoFocus={autoFocus}
      value={value}
      onChange={(e) => onChange(e.target.value.replace(/\D/g, "").slice(0, 6))}
    />
  );
}

export default function TotpEnrollment({
  setup,
  busy,
  error,
  onConfirm,
}: {
  setup: TotpSetup;
  busy: boolean;
  error: string;
  onConfirm: (code: string) => void;
}) {
  const { t } = useI18n();
  const [code, setCode] = useState("");
  const grouped = setup.secret.match(/.{1,4}/g)?.join(" ") ?? setup.secret;

  return (
    <form
      className="space-y-4"
      onSubmit={(e) => {
        e.preventDefault();
        if (code.length === 6) onConfirm(code);
      }}
    >
      <ol className="list-decimal space-y-1 pl-5 text-sm">
        <li>{t("mfa.step1")}</li>
        <li>{t("mfa.step2")}</li>
        <li>{t("mfa.step3")}</li>
      </ol>
      {/* SVG generated by our own backend (qrcode library), not user content. */}
      <div
        className="mx-auto w-48 rounded-lg bg-white p-2 [&_svg]:h-auto [&_svg]:w-full"
        dangerouslySetInnerHTML={{ __html: setup.qr_svg }}
      />
      <div className="text-center text-xs text-muted">
        <a href={setup.otpauth_uri} className="font-semibold text-accent hover:underline">
          {t("mfa.openInApp")}
        </a>
        <p className="mt-2">{t("mfa.manualKey")}</p>
        <p className="mt-1 select-all font-mono text-sm text-ink">{grouped}</p>
      </div>
      <CodeInput value={code} onChange={setCode} />
      {error && <p className="text-sm text-red-700">{error}</p>}
      <button className="btn-primary w-full" type="submit" disabled={busy || code.length !== 6}>
        {busy ? t("common.loading") : t("mfa.confirm")}
      </button>
    </form>
  );
}
